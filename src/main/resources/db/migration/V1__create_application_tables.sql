CREATE TABLE app_users (
    id UUID NOT NULL,
    username VARCHAR(40) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    display_name VARCHAR(40) NOT NULL,
    bio VARCHAR(240) NOT NULL,
    timezone VARCHAR(64) NOT NULL,
    CONSTRAINT app_users_pk PRIMARY KEY (id),
    CONSTRAINT app_users_username_uk UNIQUE (username)
);

CREATE TABLE habits (
    id UUID NOT NULL,
    name VARCHAR(60) NOT NULL,
    description VARCHAR(240) NOT NULL,
    kind VARCHAR(16) NOT NULL,
    daily_target INTEGER NOT NULL,
    unit VARCHAR(20) NOT NULL,
    user_id UUID NOT NULL,
    CONSTRAINT habits_pk PRIMARY KEY (id),
    CONSTRAINT habits_user_fk
        FOREIGN KEY (user_id) REFERENCES app_users (id)
);

CREATE INDEX habits_user_idx ON habits (user_id);

CREATE TABLE habit_progress (
    id UUID NOT NULL,
    habit_id UUID NOT NULL,
    progress_date DATE NOT NULL,
    count INTEGER NOT NULL,
    CONSTRAINT habit_progress_pk PRIMARY KEY (id),
    CONSTRAINT habit_progress_habit_date_uk UNIQUE (habit_id, progress_date),
    CONSTRAINT habit_progress_habit_fk
        FOREIGN KEY (habit_id) REFERENCES habits (id) ON DELETE CASCADE
);

CREATE INDEX habit_progress_habit_idx ON habit_progress (habit_id);

CREATE TABLE activity_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id UUID NOT NULL,
    habit_id UUID NOT NULL,
    name VARCHAR(60) NOT NULL,
    action VARCHAR(16) NOT NULL,
    count INTEGER NOT NULL,
    unit VARCHAR(20) NOT NULL,
    date DATE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT activity_events_pk PRIMARY KEY (id)
);

CREATE INDEX activity_user_sequence ON activity_events (user_id, id);
